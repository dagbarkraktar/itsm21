#
# One time script: fix stub accounting date `1999-01-21`
#
# issue: sblock complect - correct accounting date
#        monitor, ups - stub date `1999-01-21`
#

import arrow

from app_setup import db, create_app
from modules.hwdb.services import HwUnitsService
from modules.hwdb.models import HwDbModel

HW_SB_TYPE = 3


def main():
    hw_units = HwDbModel.query.all()
    count = 1
    for unit in hw_units:
        invnum = unit.invnum
        year = unit.year
        accounting = unit.accounting
        accounting_str = arrow.get(accounting).strftime('%d.%m.%Y') if accounting else ''
        if accounting_str == '21.01.1999':

            # find sblock from this complect
            sblock = HwUnitsService.get_by_invnum_n_type(
                invnum=invnum,
                type_id=HW_SB_TYPE
            )
            if sblock:
                fixed_accounting_date = sblock.accounting
            else:
                fixed_accounting_date = arrow.get(f'{year}-01-01')

            unit.accounting = fixed_accounting_date.strftime('%Y-%m-%d')
            db.session.commit()

            print(f'{count} - {invnum} - {accounting_str} - {fixed_accounting_date.strftime("%Y-%m-%d")}')
            count += 1


if __name__ == '__main__':
    app = create_app()
    with app.app_context():
        main()

